-- DMS side of customisations/gtk.lua: GTK apps follow the DMS dark/light toggle with DMS's palette.
-- DMS renders the palette through matugen, which on every run appends each *.toml in
-- ~/.config/matugen/dms/configs/ to its config, so the templates are registered there.
--
-- DMS's own GTK colors stay unused: without a user copy of adw-gtk3, its "Apply GTK colors"
-- imports dank-colors.css (a full light stylesheet in light mode) from gtk.css, which pins apps
-- to the mode they started in. customisations/gtk.lua strips that import.

local gtk = require('customisations.gtk')

local shell = gtk.setup("DMS")

local config_home = os.getenv("XDG_CONFIG_HOME") or ((os.getenv("HOME") or "") .. "/.config")

-- Re-syncs once matugen has rendered, so the themes apply on the very first render too
local POST_HOOK = [["hyprctl eval \"require('customisations.dms.gtk').sync()\""]]

local dropin = { "# Generated by Hyprland's customisations/dms/gtk.lua on every config load." }
for _, t in ipairs(shell.templates) do
    table.insert(dropin, ("[templates.hypr_gtk_%s]\ninput_path = '%s'\noutput_path = '%s'\npost_hook = %s")
        :format(t.id, t.input, t.output, POST_HOOK))
end
gtk.write_if_changed(config_home .. "/matugen/dms/configs/hypr-gtk.toml", table.concat(dropin, "\n\n") .. "\n")

return shell
