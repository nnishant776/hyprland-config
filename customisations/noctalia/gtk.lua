-- Noctalia side of customisations/gtk.lua: GTK apps follow Noctalia's dark/light toggle with
-- Noctalia's palette. Noctalia merges every *.toml in its config dir in sorted order, so the
-- templates are registered in a drop-in there; the 00- prefix lets config.toml take precedence.
--
-- Noctalia's gtk3 template re-adds its pinning noctalia.css import to gtk.css on every template
-- run, startup included, and then fires colors_changed. dconf watch ignores same-value writes,
-- so the scheme hook alone would miss startup; the colors_changed hook strips the import again.

local gtk = require('customisations.gtk')

local shell = gtk.setup("Noctalia")

local config_home = os.getenv("XDG_CONFIG_HOME") or ((os.getenv("HOME") or "") .. "/.config")
local noctalia_config_home = os.getenv("NOCTALIA_CONFIG_HOME")
if not noctalia_config_home or noctalia_config_home == "" then
    noctalia_config_home = config_home
end

local dropin = { "# Generated by Hyprland's customisations/noctalia/gtk.lua on every config load." }
for _, t in ipairs(shell.templates) do
    table.insert(dropin, ('[theme.templates.user.hypr_gtk_%s]\ninput_path = "%s"\noutput_path = "%s"')
        :format(t.id, t.input, t.output))
end
table.insert(dropin, [[[hooks]
colors_changed = "hyprctl eval \"require('customisations.noctalia.gtk').sync()\""]])
gtk.write_if_changed(noctalia_config_home .. "/noctalia/00-hypr-gtk.toml", table.concat(dropin, "\n\n") .. "\n")

return shell
